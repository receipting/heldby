@dataclass
class AdoptPlan:
    declaration_path: Path
    config_path: Path
    baseline_path: Path
    ecosystem: str
    processes: list[str]
    gateway_modules: list[str]
    other_model_files: list[str]
    existing: list[Path]

    @property
    def blocked(self) -> bool:
        return bool(self.existing)


def _guess_ecosystem(report: ScanReport) -> str:
    """Whichever language the repo actually has more of."""
    return "py" if report.languages.get("py", 0) > report.languages.get("ts", 0) else "ts"


#: Path fragments suggesting a file's job is talking to a model provider.
GATEWAY_HINTS = (
    "gateway", "ai-", "ai_", "/ai", "llm", "anthropic", "openai", "bedrock",
    "model", "provider", "completion", "inference",
)


def _choose_gateway_module(report: ScanReport) -> tuple[list[str], list[str]]:
    """Pick ONE designated gateway module, and name the rest as existing bypasses.

    Returns (gateway_modules, other_files_with_model_calls).

    The tempting shortcut is to declare every file that currently calls a model to
    be a gateway module, which makes the gate green instantly. It also makes it
    meaningless — it green-lights the bypasses by renaming them, and the tool then
    reports "every model call is made in the gateway" about a repo with calls
    scattered across a dozen files. That is exactly the kind of clean report this
    whole tool exists to distrust.

    So: one module is designated, everything else is baselined as known debt. The
    gate still passes on day one, but through an explicit shrink-only list that
    says out loud what has not been fixed yet.
    """
    counts: dict[str, int] = {}
    for site in report.sites:
        if site.kind == "model" and site.why in {"symbol", "member", "url", "url-literal"}:
            counts[site.file] = counts.get(site.file, 0) + 1
    if not counts:
        return [], []

    def rank(path: str) -> tuple[int, int]:
        hinted = 1 if any(hint in path.lower() for hint in GATEWAY_HINTS) else 0
        return (hinted, counts[path])

    best = max(sorted(counts), key=rank)
    return [best], sorted(f for f in counts if f != best)


def plan(root: Path, catalog: Catalog) -> AdoptPlan:
    report = scan(root, catalog, ignore_declarations=True)
    ecosystem = _guess_ecosystem(report)

    names = sorted({n for names in report.labels.values() for n in names})
    gateways, others = _choose_gateway_module(report)
    declaration = root / ("ai_register.py" if ecosystem == "py" else "ai-register.ts")
    config = root / "heldby.yml"
    baseline = root / ".heldby-baseline.json"

    return AdoptPlan(
        declaration_path=declaration,
        config_path=config,
        baseline_path=baseline,
        ecosystem=ecosystem,
        processes=names,
        gateway_modules=gateways,
        other_model_files=others,
        existing=[p for p in (declaration, config) if p.exists()],
    )


def _ts_entry(name: str) -> str:
    return (
        f"  {name!r}: {{\n"
        f"    class: 'read',        // CHECK THIS. Read < Converse < Decide < Write.\n"
        f"    model: '',            // the model this call site pins\n"
        f"    does: '',             // one line, for the register a customer reads\n"
        f"    reaches: [],          // what it can reach when it is wrong\n"
        f"    heldBy: '',           // empty means NOTHING holds it, and says so\n"
        f"  }},\n"
    )


def _py_entry(name: str) -> str:
    return (
        f'    "{name}": {{\n'
        f'        "class": "read",   # CHECK THIS. Read < Converse < Decide < Write.\n'
        f'        "model": "",       # the model this call site pins\n'
        f'        "does": "",        # one line, for the register a customer reads\n'
        f'        "reaches": [],     # what it can reach when it is wrong\n'
        f'        "held_by": "",     # empty means NOTHING holds it, and says so\n'
        f"    }},\n"
    )


def render_declaration(plan_: AdoptPlan) -> str:
    names = plan_.processes or ["unnamed-process"]
    if plan_.ecosystem == "py":
        return PY_TEMPLATE.format(
            actions="\n".join(f'    "{a}",' for a in sorted(ACTIONS)),
            processes="".join(_py_entry(n) for n in names),
            feature_names="\n".join(f'    "{n}",' for n in names),
        )
    return TS_TEMPLATE.format(
        actions="\n".join(f"  | {a!r}" for a in sorted(ACTIONS)),
        processes="".join(_ts_entry(n) for n in names),
    )


def render_config(plan_: AdoptPlan) -> str:
    modules = plan_.gateway_modules or ["src/"]
    listed = "\n".join(f"  - {m}" for m in modules)
    return f"""\
# heldby configuration. See https://github.com/receipting/heldby
#
# gateway_modules: the ONLY places a model client may be constructed or a provider
# host named. heldby lint fails on a model call anywhere else.
#
# ONE module was designated, chosen as the likeliest candidate from where model
# calls are made today. Every other file that calls a model is recorded in the
# baseline below as known debt, NOT promoted to a gateway — declaring them all to
# be gateways would make this gate pass by renaming the problem.
#
# Change this if the tool picked wrong. It guessed.
gateway_modules:
{listed}

# Excluded paths are NOT covered by the gate's claim, and heldby says so in its
# output every time it passes. A scope you cannot see is a scope you cannot audit.
exclude: []

# Pre-existing bypasses, accepted deliberately. This file may only SHRINK.
baseline: .heldby-baseline.json

declaration: {plan_.declaration_path.name}
"""
