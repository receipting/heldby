"""Write the findings back into the codebase as declarations, plus a gate.

Inference is the right tool for a repo you do not control and cannot mandate
anything about — which is exactly where you are the first time you point this at a
codebase. For code you *own*, declaring and enforcing beats inferring: it is
complete, it works in every language, and it fails on the exact line instead of
reporting "no path found".

So `adopt` graduates a repo off inference. After it runs, the register is
generated from the code's own declarations and the next run is declared rather
than guessed. That converts "tell us before you add an AI service" from something
an annual sweep discovers into a compile error.

Two decisions worth knowing about.

**It generates the wrapper, not just the declaration.** The load-bearing part is
not the list of processes; it is that every call site must pass a `feature`
argument whose type is `keyof typeof AI_PROCESSES`. Without the wrapper the clever
bit does not come with it, and the declaration is just a comment that happens to
compile.

**`held_by` is generated EMPTY.** Not "TODO", not "under review" — empty. An empty
control renders as **nothing** in the register, which is the honest state of a
process nobody has yet written a control for. Pre-filling it with placeholder
reassurance would launder an unknown into a claim, in the one column that matters.

**Nothing is published.** `adopt` vendors a single file into the repo. No package
to install, no registry to authenticate against, no version to keep in step —
because a public tool cannot assume a company has, or wants, an internal package
registry, and a shared dependency is the part of this that would rot.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from .catalog import Catalog
