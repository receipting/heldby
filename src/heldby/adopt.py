TS_TEMPLATE = '''\
// Generated by heldby (https://github.com/receipting/heldby). Vendored on purpose:
// no package to install and no version to keep in step.
//
// This file is the source of truth for this repo's AI register. Two rules:
//
//   1. Every model call passes a `feature` whose type is `AIFeature`, so a new AI
//      call cannot ship without adding an entry below — it will not compile.
//   2. `heldBy` is the only column that matters. Name the specific thing standing
//      between the model's output and a real-world effect. Not "we have guardrails".
//      The entry has to survive an auditor reading the code next to it. If the
//      honest answer is nothing, leave it empty — the register will say so.

export type AIClass = 'read' | 'decide' | 'converse' | 'write'

/**
 * Read     — turns a document or message into structured data, checked against
 *            something real. If it cannot be checked against the world, not Read.
 * Decide   — proposes an action with a consequential effect. No person on the fast
 *            path by design; bounded by deterministic gates plus a threshold.
 * Converse — answers the person who asked, them and us and nobody else, and does
 *            nothing. All three closed-loop tests must hold.
 * Write    — produces prose the system carries to someone else. A named person
 *            edits and releases it, and the record says who.
 *
 * Where a process spans two, the STRICTER governs: Read < Converse < Decide < Write.
 */
export type ProtectedAction =
{actions}

export interface AIProcess {{
  /** The stricter class, where a process spans two. */
  class: AIClass
  /** The model this call site pins. */
  model: string
  /** One line, written for the register a customer reads. */
  does: string
  /** What this can reach when it is wrong. */
  reaches: readonly ProtectedAction[]
  /** The specific control between the output and the effect. Empty means nothing does. */
  heldBy: string
}}

/**
 * Identity function, and the `const` type parameter is doing the work: it
 * validates every entry against AIProcess AND preserves the keys as literals, so
 * `AIFeature` below is a union of the actual process names rather than `string`.
 */
export function defineProcesses<const T extends Record<string, AIProcess>>(processes: T): T {{
  return processes
}}

export const AI_PROCESSES = defineProcesses({{
{processes}}})

/** The union of declared process names. A call site cannot pass anything else. */
export type AIFeature = keyof typeof AI_PROCESSES

/**
 * Pass this into your model client's metadata. It exists so that `feature` is
 * REQUIRED and TYPED at every call site — which is the whole mechanism. Construct
 * your provider client in this file too, and `heldby lint` will hold that line.
 */
export function modelMeta(feature: AIFeature): {{ process: string; model: string }} {{
  return {{ process: String(feature), model: AI_PROCESSES[feature].model }}
}}
'''

